#!/usr/bin/env python3
"""Reproduce the real-time RFI mask saved in a CHIME acquisition, using the old pipeline.

    misc/chimefrb/01-reproduce-rfimask.py <acqdir> <rfi_chain.json> [-p PRESCALE] [--nfiles N] [-v]

    acqdir          directory of chunk_NNNNNNNN.msg files written by the CHIME L1 server,
                    e.g. /scratch/tweiss_rfi/frb_B0037+56_down3_2026-05-22-09-26/beam_3146
    rfi_chain.json  the jsonized RFI transform chain that the L1 server ran, e.g.
                    misc/chimefrb/configs/21-03-07-low-latency-uniform-badchannel-mask-noplot.json

Each file holds 1024 samples of raw 16K-channel intensity data, plus the RFI mask that the
L1 server computed from that data in real time, at the 1K resolution of the chain's
sub-pipeline.  This script runs the same chain, built from the same json by the old CHIME
code (rebuilt for this machine by misc/chimefrb/build_oldpipe.sh), on the raw data, and
compares the mask it gets with the saved one.  It prints the percentage of mask samples in
each of the four (saved, new) x (masked, unmasked) combinations.

The L1 server ran the chain in 4096-sample chunks aligned to ichunk % 4 == 0, so the
files are used in groups of four with that alignment: files at either end that do not
complete a group are dropped (and named), and the file sequence must have no gaps.

Needs the old pipeline built (misc/chimefrb/build_oldpipe.sh).  The work happens under the
old pipeline's python 2.7; invoked from python 3, the script re-executes itself there and
says so.  No pirate code is involved.

Exit status: 0 if the masks are identical, 2 if they differ, 1 for a usage or data error.
"""

from __future__ import print_function, division

import argparse
import json
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))          # misc/chimefrb
OLDPIPE = os.path.join(HERE, 'oldpipe')                    # the old-pipeline build, gitignored

NT = 1024                    # samples per file (ch_frb_io::constants::nt_per_assembled_chunk)
FILES_PER_RFI_CHUNK = 4      # the L1 server's RFI chunk is 4096 samples ('nt_align' in its config)
REALTIME_PRESCALE = 1.0e-4   # 'intensity_prescale' in ch_frb_l1/l1_configs/l1_production_8beam.yaml

FILENAME_RE = re.compile(r'^chunk_(\d{8})\.msg$')

# Positions in the 21-element array of a version-2 assembled_chunk msgpack file
# (ch_frb_io/assembled_chunk_msgpack.hpp).
MSG_NFIELDS = 21
MSG_VERSION = 1
MSG_BEAM_ID = 4
MSG_NUPFREQ = 5
MSG_FPGA_COUNTS_PER_SAMPLE = 7
MSG_FPGA_BEGIN = 11
MSG_BINNING = 13
MSG_NRFIFREQ = 18
MSG_HAS_RFI_MASK = 19
MSG_RFI_MASK = 20


def die(msg):
    print('ERROR: ' + msg, file=sys.stderr)
    sys.exit(1)


# -------------------------------------------------------------------------------------------------
#
# Stage 1 (python 3): hand over to the old pipeline's python 2.7.


def reexec_under_old_pipeline():
    """Replaces this process with the old pipeline's python 2.7 running the same command line.

    Does not return.  The old rf_pipelines exists only as a python 2.7 extension, so the real
    work must happen there, with oldpipe/env.sh sourced so that its libraries are found.
    """

    envsh = os.path.join(OLDPIPE, 'env.sh')
    if not os.path.exists(envsh):
        die("no old-pipeline build found at %s.\n"
            "       Run misc/chimefrb/build_oldpipe.sh first (about a minute)." % OLDPIPE)

    conda_env = None
    with open(envsh) as f:
        for line in f:
            m = re.match(r'export CHIMEFRB_ENV=(\S+)', line)
            if m:
                conda_env = m.group(1)
    if conda_env is None:
        die("could not find CHIMEFRB_ENV in %s; was it generated by build_oldpipe.sh?" % envsh)

    python2 = os.path.join(conda_env, 'bin', 'python')
    if not os.path.exists(python2):
        die("the old pipeline's conda env is missing (%s).\n"
            "       See 'Prerequisites' in misc/chimefrb/README.md." % conda_env)

    script = os.path.abspath(__file__)
    print("This script does its work under the old pipeline's python 2.7.  Re-executing as\n"
          "    . %s && %s %s ...\n" % (envsh, python2, script))
    sys.stdout.flush()

    # Lets stage 2 notice if the re-exec somehow did not land in python 2, instead of looping.
    os.environ['REPRODUCE_RFIMASK_REEXEC'] = '1'

    # In 'bash -c CMD ARG0 ARG1 ...', $0 is ARG0 and "$@" is ARG1 onwards.
    os.execvp('bash', ['bash', '-c', '. "$0" && exec "$@"', envsh, python2, script] + sys.argv[1:])


