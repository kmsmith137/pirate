# Stage 2 (python 2.7): imports.


def import_old_pipeline():
    """Imports numpy, msgpack and the old rf_pipelines, diagnosing whatever is missing."""

    global np, msgpack, rf_pipelines

    if not os.environ.get('OLDPIPE'):
        die("run this script with python 3 (it will re-execute itself under the old pipeline's\n"
            "       python 2.7), or source misc/chimefrb/oldpipe/env.sh first.")
    try:
        import numpy as np
        import msgpack
    except ImportError as e:
        die("%s.\n       The old pipeline's conda env is incomplete; see 'Prerequisites' in\n"
            "       misc/chimefrb/README.md." % e)
    try:
        import rf_pipelines
    except ImportError as e:
        die("import rf_pipelines failed: %s.\n"
            "       The build in %s looks stale or incomplete; rerun misc/chimefrb/build_oldpipe.sh." % (e, OLDPIPE))


# The two transforms below subclass the old rf_pipelines.wi_transform, which exists only in
# stage 2.  Stage 1 never instantiates them, so there they get a placeholder base class.
if sys.version_info[0] == 2:
    import_old_pipeline()
    _transform_base = rf_pipelines.wi_transform
else:
    _transform_base = object


# -------------------------------------------------------------------------------------------------
#
# The two transforms added to the chain.


class prescale_transform(_transform_base):
    """Multiplies the intensity by a constant, as the L1 server's network stream does when decoding.

    The old file stream has no prescale option, so the L1 server's 'intensity_prescale' (1e-4 in
    production) is applied here instead, one step later, as a separate transform.  The chain's
    mask does not depend on the intensity scale mathematically; this exists to keep the
    floating-point arithmetic in the same regime as the real-time run.
    """

    def __init__(self, prescale):
        rf_pipelines.wi_transform.__init__(self, 'prescale_transform')
        self.nt_chunk = NT
        self.prescale = np.float32(prescale)

    def _process_chunk(self, intensity, weights, pos):
        intensity *= self.prescale


class mask_comparator(_transform_base):
    """Compares (weights > 0) with the saved masks, one saved file per call, and accumulates counts.

    This goes right after the chain's last mask_counter, inside the 1K sub-pipeline, so that it
    sees exactly the weights that the L1 server's mask_counter packed into the saved files.
    With nt_chunk = 1024 at the sub-pipeline's native time resolution, call number i is saved
    file number i.

    After the run: 'counts' is the 2x2 array of sample counts indexed [saved][new], with 0 =
    masked and 1 = unmasked, and 'disagreements' lists (name, nsamples, nrows) for each file
    whose masks differ, nrows being the number of 1024-sample rows that differ in every sample.
    """

    def __init__(self, names, saved_masks, verbose):
        rf_pipelines.wi_transform.__init__(self, 'mask_comparator')
        self.nt_chunk = NT
        self.names = names
        self.saved_masks = saved_masks
        self.verbose = verbose
        self.ncalls = 0
        self.counts = np.zeros((2, 2), dtype=np.int64)
        self.disagreements = []
        self.t0 = time.time()

    def _process_chunk(self, intensity, weights, pos):
        if pos % NT != 0:
            raise RuntimeError('mask_comparator: pos=%d is not a multiple of %d' % (pos, NT))
        i = pos // NT
        if i >= len(self.names):
            raise RuntimeError('mask_comparator: the chain produced more chunks than there are saved files (%d)' % len(self.names))

        saved = unpack_mask(self.saved_masks[i])
        new = (weights > 0.0)
        if new.shape != saved.shape:
            raise RuntimeError('mask_comparator: shape mismatch, saved %s vs new %s' % (saved.shape, new.shape))

        n11 = np.count_nonzero(saved & new)
        n10 = np.count_nonzero(saved & ~new)
        n01 = np.count_nonzero(~saved & new)
        n00 = saved.size - n11 - n10 - n01
        self.counts += np.array([[n00, n01], [n10, n11]], dtype=np.int64)

        if n10 + n01 > 0:
            nrows = int(np.count_nonzero((saved != new).all(axis=1)))
            self.disagreements.append((self.names[i], n10 + n01, nrows))

        self.ncalls += 1
        if self.verbose:
            print('    %s: %d samples disagree (%d whole rows), unmasked fraction saved %.4f new %.4f'
                  % (self.names[i], n10 + n01, self.disagreements[-1][2] if n10 + n01 else 0, saved.mean(), new.mean()))
        elif self.ncalls % 200 == 0:
            print('    %d / %d files, %.0f s' % (self.ncalls, len(self.names), time.time() - self.t0))
            sys.stdout.flush()


def unpack_mask(packed):
    """(nfreq, NT/8) packed bytes -> (nfreq, NT) bool, True = unmasked.

    Bit i of byte j is sample 8j+i: rf_kernels::mask_counter packs least significant bit first,
    while numpy unpacks most significant bit first (numpy 1.16 has no bitorder= argument), so
    each byte's eight bits are reversed.
    """

    bits = np.unpackbits(packed[:, :, np.newaxis], axis=2)[:, :, ::-1]
    return bits.reshape(packed.shape[0], NT).astype(bool)


