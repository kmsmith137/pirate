"""
Tests of the frequency-subband machinery (run via 'test --sb').

Two tests:

  - test_frequency_subbands_parity(): the C++ FrequencySubbands and its python twin
    (pirate_frb.cuda_generator.FrequencySubbands) must agree, in every respect that both
    implementations compute. They are two transcriptions of one specification, and the split
    is load-bearing: makefile_helper.py uses the python one at BUILD time to decide which
    kernels to compile, while DedispersionConfig/DedispersionPlan use the C++ one at RUN
    time to decide which kernel to ask for. A divergence is silent when it happens, and
    surfaces much later -- as "Kernel not found in registry" for some config, or as a
    compiled kernel whose load-time self-check throws.

    Note the autogenerated kernels already emit xassert(vec_equal(fs.m_to_n, ...)) and
    friends, which checks the constructor tables at load time. But that only covers the
    subband_counts shapes this build happens to compile, and covers nothing at all in a
    build with the kernel flags turned off. This test sweeps the shapes exhaustively, and
    covers the parts no kernel checks: validate_subband_counts(), n_to_mbase, and the
    python-only helpers that the code generators call.

  - test_subband_property(): for each config, every tree's subband set must be a subset of
    its primary tree's main (early_trigger_level=0) tree, and every main tree must have the
    same subband set as tree (0,0). I.e. time-downsampling neither adds nor removes
    subbands, and an early trigger can remove them but never add one. Subbands are compared
    as toplevel tree-freq ranges, which is what makes trees of different rank comparable.

    The "never add" half is the one with teeth: it is why an early-trigger tree's own full
    band has to be a band the config already declares, which is what
    FrequencySubbands.can_early_trigger() and DedispersionConfig.validate() enforce.
"""

import os
import glob
import random
import itertools

from ..pirate_pybind11 import DedispersionConfig, DedispersionPlan, FrequencySubbands
from ..cuda_generator import FrequencySubbands as PyFrequencySubbands
from ..utils import atomic_print


####################################################################################################
#
# C++ / python parity. Enumeration helpers.


def _max_bands(pf_rank, level):
    # Level 0 is special (non-overlapping bands).
    return (2**(pf_rank+1-level) - 1) if (level > 0) else 2**pf_rank


def _all_counts(pf_rank):
    """Yields every valid subband_counts vector with this pf_rank."""

    ranges = [ range(_max_bands(pf_rank, level) + 1) for level in range(pf_rank) ]
    for combo in itertools.product(*ranges):
        yield list(combo) + [1]


def _random_counts(pf_rank):
    """One random valid subband_counts vector with this pf_rank."""

    return [ random.randint(0, _max_bands(pf_rank, level)) for level in range(pf_rank) ] + [1]


####################################################################################################
#
# C++ / python parity. The three comparisons: validate_subband_counts(), the constructor
# tables, and restrict_subband_counts()/can_early_trigger().


def _compare_validate(subband_counts):
    """validate_subband_counts(): both implementations accept, or both reject.

    Returns True if both accept. This is the gate that decides which counts vectors exist
    at all, so a divergence here is upstream of everything else in this file.
    """

    def accepts(cls):
        try:
            cls.validate_subband_counts(list(subband_counts))
            return True
        except RuntimeError:
            return False

    cpp_ok = accepts(FrequencySubbands)
    py_ok = accepts(PyFrequencySubbands)

    assert cpp_ok == py_ok, \
        f"validate_subband_counts({subband_counts}): C++ {'accepts' if cpp_ok else 'rejects'}, " \
        f"python {'accepts' if py_ok else 'rejects'}"

    return cpp_ok


def _near_misses(subband_counts):
    """Invalid variants of a valid counts vector -- where a divergence would hide.

    (A sweep over valid vectors only would pass even if one implementation had no bounds
    checks at all.)
    """

    pf_rank = len(subband_counts) - 1

    for level in range(pf_rank + 1):
        v = list(subband_counts)
        v[level] = _max_bands(pf_rank, level) + 1   # one more band than fits
        yield v

        v = list(subband_counts)
        v[level] = -1                               # negative count
        yield v

    # The top level must be exactly 1: every tree searches its own full band.
    for c in (0, 2):
        yield list(subband_counts[:-1]) + [c]

    # pf_rank above the peak-finding kernel's maximum (constants::max_peak_finding_rank).
    yield [0] * 5 + list(subband_counts)


def _compare_tables(subband_counts):
    """The constructor's derived tables, i.e. every member both classes compute.

    The two lay them out differently -- the C++ splits pairs into two parallel vectors, and
    stores only the BASE of each multiplet range -- so the comparison has to convert rather
    than compare field by field.
    """

    cpp = FrequencySubbands(list(subband_counts))
    py = PyFrequencySubbands(subband_counts = list(subband_counts))
    ctx = f"FrequencySubbands({subband_counts})"

    assert list(cpp.subband_counts) == list(py.subband_counts), ctx
    assert cpp.pf_rank == py.pf_rank, f"{ctx}: pf_rank {cpp.pf_rank} vs {py.pf_rank}"
    assert cpp.N == py.N, f"{ctx}: N {cpp.N} vs {py.N}"
    assert cpp.M == py.M, f"{ctx}: M {cpp.M} vs {py.M}"

    # (multiplet) -> (frequency subband, fine dm).
    cpp_m_to_nd = list(zip(cpp.m_to_n, cpp.m_to_d))
    py_m_to_nd = [tuple(x) for x in py.m_to_nd]
    assert cpp_m_to_nd == py_m_to_nd, f"{ctx}: m_to_nd {cpp_m_to_nd} vs {py_m_to_nd}"

    # (frequency subband) -> coarse-freq range.
    cpp_frange = list(zip(cpp.n_to_flo, cpp.n_to_fhi))
    py_frange = [tuple(x) for x in py.n_to_frange]
    assert cpp_frange == py_frange, f"{ctx}: n_to_frange {cpp_frange} vs {py_frange}"

    # (frequency subband) -> multiplet range. The C++ stores the base only; the range is
    # (mbase, mbase + 2^level), and 2^level is the width of the band in coarse-freq
    # channels. NOTE no autogenerated kernel checks this member, unlike the two above.
    cpp_mrange = [(mb, mb + fhi - flo) for mb, (flo, fhi) in zip(cpp.n_to_mbase, cpp_frange)]
    py_mrange = [tuple(x) for x in py.n_to_mrange]
    assert cpp_mrange == py_mrange, f"{ctx}: n_to_mrange {cpp_mrange} vs {py_mrange}"

    # get_band_index_range() and max_bands_at_level() are python-only helpers, called by the
    # code generators to place bands. Check them against the C++ tables for every band that
    # exists. (Sweeping counts vectors covers every (level, b) pair with b < max_bands.)
    n = 0
    for level in range(py.pf_rank + 1):
        assert py.max_bands_at_level(level) == _max_bands(py.pf_rank, level), \
            f"{ctx}: max_bands_at_level({level})"
        for b in range(subband_counts[level]):
            got = tuple(py.get_band_index_range(level, b))
            assert got == cpp_frange[n], \
                f"{ctx}: get_band_index_range({level},{b}) is {got}, C++ subband {n} is {cpp_frange[n]}"
            n += 1
    assert n == cpp.N, ctx

    # 'fstr' has no C++ counterpart -- it names the autogenerated kernel FILES, which is how
    # the build identifies a shape -- so the check available here is a round trip. Leading
    # zeros are meaningful and must survive it: 'n0_n0_n3_n2_n1' and 'n3_n2_n1' are
    # different kernels.
    assert PyFrequencySubbands.from_fstr(py.fstr).subband_counts == list(subband_counts), \
        f"{ctx}: fstr round trip failed (fstr={py.fstr})"


def _compare_restrict(subband_counts, et_level):
    """restrict_subband_counts() and can_early_trigger(), for one (counts, et_level) pair."""

    cpp_ok = FrequencySubbands.can_early_trigger(subband_counts, et_level)
    py_ok = PyFrequencySubbands.can_early_trigger(subband_counts, et_level)

    assert cpp_ok == py_ok, \
        f"can_early_trigger({subband_counts}, {et_level}): C++ says {cpp_ok}, python says {py_ok}"

    if not cpp_ok:
        # Both must refuse. (A silent difference here would be as bad as a different result:
        # it decides which early-trigger levels a config may declare.)
        for name, cls in [('C++', FrequencySubbands), ('python', PyFrequencySubbands)]:
            try:
                cls.restrict_subband_counts(subband_counts, et_level)
            except RuntimeError:
                continue
            raise AssertionError(f"{name} restrict_subband_counts({subband_counts}, {et_level}) "
                                 f"should have thrown (can_early_trigger is False)")
        return None

    cpp = list(FrequencySubbands.restrict_subband_counts(subband_counts, et_level))
    py = list(PyFrequencySubbands.restrict_subband_counts(subband_counts, et_level))

    assert cpp == py, \
        f"restrict_subband_counts({subband_counts}, {et_level}): C++ gives {cpp}, python gives {py}"

    # Two invariants of the rule itself, cheap to check here and independent of the two
    # implementations agreeing with each other.
    assert len(cpp) == len(subband_counts) - et_level, \
        f"restrict_subband_counts({subband_counts}, {et_level}) = {cpp}: wrong pf_rank"

    for level, count in enumerate(cpp):
        assert count <= subband_counts[level], \
            f"restrict_subband_counts({subband_counts}, {et_level}) = {cpp}: level {level} " \
            f"gained bands, which would ADD a subband to the search"

    return cpp


def _sweep(subband_counts, seen):
    """All three comparisons, for one valid counts vector. Returns the number made."""

    n = 0

    for v in _near_misses(subband_counts):
        _compare_validate(v)
        n += 1

    assert _compare_validate(subband_counts), f"{subband_counts} should be valid"
    _compare_tables(subband_counts)
    n += 2

    for et_level in range(len(subband_counts) + 1):   # +1 so the out-of-range case is covered
        restricted = _compare_restrict(subband_counts, et_level)
        n += 1

        # The restricted counts are what a tree's FrequencySubbands is actually built from
        # (in the DedispersionPlan constructor), so compare their tables too. Deduped: the
        # same restricted vector comes up over and over across the sweep.
        if (restricted is not None) and (tuple(restricted) not in seen):
            seen.add(tuple(restricted))
            _compare_tables(restricted)
            n += 1

    return n


def test_frequency_subbands_parity(nrandom=400, sweep_low_ranks=True):
    """C++ vs python FrequencySubbands: validate, the constructor tables, and the tree rule.

    TWO HALVES AT TWO CADENCES. The pf_rank <= 3 sweep is exhaustive and therefore identical
    on every call, so the caller runs it once per invocation (notes/unit_tests.md point 11)
    and spends the freed budget on 'nrandom'. At pf_rank == 4 the space is 8704 vectors, so
    doubling nrandom to 400 takes the fraction never seen over 100 iterations from
    exp(-200*100/8704) = 10% to 1%.
    """

    ncmp = 0
    seen = set()

    # Exhaustive at pf_rank <= 3 (312 counts vectors).
    if sweep_low_ranks:
        for pf_rank in range(4):
            for subband_counts in _all_counts(pf_rank):
                ncmp += _sweep(subband_counts, seen)

    # Sampled at pf_rank == 4 (8704 counts vectors, too many to sweep every iteration).
    for _ in range(nrandom):
        ncmp += _sweep(_random_counts(4), seen)

    atomic_print(f'test_frequency_subbands_parity: {ncmp} comparisons agree'
                 f' ({nrandom} random pf_rank=4 vectors'
                 f'{", plus the exhaustive pf_rank <= 3 sweep" if sweep_low_ranks else ""})')


####################################################################################################
#
# Property (*): bands(ipri,iet) <= bands(ipri,0) == bands(0,0).
#
# This is a property of the config-to-tree construction, and notes/variance_map.tex derives it
# there (appendix "Variance maps of a config's trees are row-restrictions of one another",
# fact (F2)), so the test is not establishing something that might have turned out otherwise.
# What it checks is that DedispersionPlan.{n,m}_index_mapping() -- which every caller of the
# property goes through -- implement the containment correctly, in both directions, over a
# wide spread of configs. The appendix cites this test as its witness, which is now
# belt-and-braces rather than the only evidence.


def _check_subband_property(config, label):
    """Property (*), expressed through the index-mapping helpers.

    m_index_mapping(parent, child) throws unless every band of 'child' is a band of 'parent'
    (and unless matched bands have the same level), so a successful call IS the containment
    assertion -- and a stricter one than a set comparison, which does not see levels.
    """

    # A "minimal" plan: subband geometry is pure arithmetic, and we do not want to require
    # that every tree's cdd2 kernel is compiled into this build.
    plan = DedispersionPlan(config, mega_ringbuf=False, gpu_kernels=False)

    itrees = {}
    for (itree, tree) in enumerate(plan.trees):
        itrees[(tree.primary_tree_index, tree.early_trigger_level)] = itree

    ibase = itrees[(0,0)]

    for (ipri, iet), itree in sorted(itrees.items()):
        if iet == 0:
            # Set EQUALITY, which a single call cannot express: one call gives containment,
            # so equality needs both argument orders. Both succeeding additionally shows the
            # mapping is a bijection.
            for (a, b, why) in [(ibase, itree, f'tree (ipri={ipri}, iet=0) searches a band that tree (0,0) does not'),
                                (itree, ibase, f'tree (0,0) searches a band that tree (ipri={ipri}, iet=0) does not')]:
                try:
                    plan.m_index_mapping(a, b)
                except RuntimeError as e:
                    raise AssertionError(f'{label}: {why}. Time-downsampling must not change'
                                         f' the subband set.\n  {e}') from e
        else:
            try:
                plan.m_index_mapping(itrees[(ipri,0)], itree)
            except RuntimeError as e:
                raise AssertionError(f'{label}: tree (ipri={ipri}, iet={iet}) searches a band'
                                     f' that tree (ipri={ipri}, iet=0) does not. An early'
                                     f' trigger may remove subbands, but must never add'
                                     f' one.\n  {e}') from e


def test_subband_property(nrandom=8, shipped=True):
    """Property (*) on random configs, plus the shipped configs if they are reachable.

    The shipped-config half re-parses nine fixed yaml files and rebuilds nine fixed plans,
    so it says exactly the same thing on every call and the caller runs it once per
    invocation. The random half runs every iteration.
    """

    # gpu_valid=False: this test needs no kernels, and the !gpu_valid path generates deeper
    # early-trigger ladders (it is not filtered by which cdd2 kernels happen to be compiled),
    # which is exactly where the property has content.
    for i in range(nrandom):
        config = DedispersionConfig.make_random(max_toplevel_rank=12, gpu_valid=False)
        _check_subband_property(config, f'make_random() #{i}')

    # The shipped configs, when the test is run from a source checkout. (pirate_frb does not
    # package configs/, so this is best-effort extra coverage rather than a requirement.)
    paths = sorted(glob.glob('configs/dedispersion/*.yml')) if shipped else []

    for path in paths:
        config = DedispersionConfig.from_yaml(path)
        _check_subband_property(config, os.path.basename(path))

    atomic_print(f'test_subband_property: {nrandom} random configs + {len(paths)} shipped configs')


def run_all():
    test_frequency_subbands_parity()
    test_subband_property()
